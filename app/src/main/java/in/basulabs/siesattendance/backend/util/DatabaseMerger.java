	/**
	 * The column names of a live table, read from the schema rather than listed in code. This is
	 * what lets a column added by a future migration come across without this class changing.
	 */
	@NonNull
	private static List<String> columnsOf(@NonNull SupportSQLiteDatabase db,
	                                      @NonNull String table) {

		List<String> columns = new ArrayList<>();

		try (Cursor cursor = db.query("PRAGMA main.table_info(" + table + ")")) {
			int nameIndex = cursor.getColumnIndexOrThrow("name");
			while (cursor.moveToNext()) {
				columns.add(cursor.getString(nameIndex));
			}
		}
		return columns;
	}

	/** First column of the first row as a Long, or null when there is no row or the value is null. */
	@Nullable
	private static Long queryLong(@NonNull SupportSQLiteDatabase db, @NonNull String sql,
	                              @NonNull Object[] args) {

		try (Cursor cursor = db.query(sql, args)) {
			return cursor.moveToFirst() && !cursor.isNull(0) ? cursor.getLong(0) : null;
		}
	}

	/** First column of the first row as a String, or null when there is no row or it is null. */
	@Nullable
	private static String queryString(@NonNull SupportSQLiteDatabase db, @NonNull String sql,
	                                  @NonNull Object[] args) {

		try (Cursor cursor = db.query(sql, args)) {
			return cursor.moveToFirst() && !cursor.isNull(0) ? cursor.getString(0) : null;
		}
	}

	/** A column's value, treating both a missing column and a null value as null. */
	@Nullable
	private static String stringOrNull(@NonNull Cursor cursor, @NonNull String column) {

		int index = cursor.getColumnIndex(column);
		return index < 0 || cursor.isNull(index) ? null : cursor.getString(index);
	}

	/**
	 * Removes a database file along with its write-ahead log and shared-memory files. Leaving a
	 * sidecar behind would let SQLite replay a journal against a file that has been replaced.
	 */
	private static void deleteWithSidecars(@NonNull File file) {
		//noinspection ResultOfMethodCallIgnored
		file.delete();
		//noinspection ResultOfMethodCallIgnored
		new File(file.getPath() + "-wal").delete();
		//noinspection ResultOfMethodCallIgnored
		new File(file.getPath() + "-shm").delete();
	}
